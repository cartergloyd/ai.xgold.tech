#!/usr/bin/env node
/**
 * build-work.mjs — publish xGold work entries.
 *
 * Reads   content/work/*.json
 * Writes  work/<slug>.html            one page per published entry
 *         work/index.json             machine-readable list of published entries
 *         solutions.html              replaces the block between WORK:START and WORK:END
 *
 * No dependencies. Run:  node scripts/build-work.mjs [--include-drafts]
 * Entries with "draft": true are skipped unless --include-drafts is passed.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CONTENT = path.join(ROOT, 'content', 'work');
const OUT = path.join(ROOT, 'work');
const SOLUTIONS = path.join(ROOT, 'solutions.html');
const INCLUDE_DRAFTS = process.argv.includes('--include-drafts');
const GENERATED = '<!-- generated by scripts/build-work.mjs; edit content/work/*.json instead -->';

const AREAS = { documents: 'Documents', reporting: 'Reporting', integration: 'Integration', support: 'Support', agents: 'Agents', governance: 'Governance' };
const TYPES = ['Implementation', 'Proof of concept', 'Article', 'Note'];
const STATUSES = ['Live', 'Pilot', 'Concept', 'Published', 'Retired'];
const SPEC_FIELDS = [['problem', 'Problem'], ['changed', 'Changed'], ['systems', 'Systems'], ['measured', 'Measured'], ['result', 'Result']];

/* ---------- text helpers ---------- */
const esc = (s) => String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
const safeUrl = (u) => /^(https?:\/\/|\/|#|\.\.?\/)/.test(u) ? u : '#';
/** Escape, then allow **bold**, *italic*, `code` and [text](url). Nothing else. */
function inline(s) {
  let t = esc(s);
  t = t.replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, (_, text, url) => {
    const ext = /^https?:\/\//.test(url) ? ' target="_blank" rel="noopener noreferrer"' : '';
    return `<a href="${esc(safeUrl(url))}"${ext}>${text}</a>`;
  });
  t = t.replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>');
  t = t.replace(/(^|[\s(])\*([^*\s][^*]*)\*/g, '$1<em>$2</em>');
  t = t.replace(/`([^`]+)`/g, '<code>$1</code>');
  return t;
}
function fmtDate(iso) {
  const d = new Date(iso + 'T12:00:00Z');
  return d.toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC' });
}
const rel = (base, src) => /^https?:\/\//.test(src) ? src : base + src.replace(/^\/+/, '');

/* ---------- load + validate ---------- */
function load() {
  if (!fs.existsSync(CONTENT)) return [];
  const entries = [];
  for (const f of fs.readdirSync(CONTENT).filter((n) => n.endsWith('.json')).sort()) {
    const file = path.join(CONTENT, f);
    let e;
    try { e = JSON.parse(fs.readFileSync(file, 'utf8')); } catch (err) { fail(`${f}: invalid JSON (${err.message})`); }
    const errs = [];
    if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(e.slug || '')) errs.push('slug must be lowercase letters, digits and hyphens');
    if (!e.title) errs.push('title is required');
    if (!e.summary) errs.push('summary is required');
    if (!TYPES.includes(e.type)) errs.push(`type must be one of: ${TYPES.join(', ')}`);
    if (!AREAS[e.area]) errs.push(`area must be one of: ${Object.keys(AREAS).join(', ')}`);
    if (!/^\d{4}-\d{2}-\d{2}$/.test(e.date || '')) errs.push('date must be YYYY-MM-DD');
    if (e.status && !STATUSES.includes(e.status)) errs.push(`status must be one of: ${STATUSES.join(', ')}`);
    if (e.spec) for (const [k] of SPEC_FIELDS) if (!e.spec[k]) errs.push(`spec.${k} is required when spec is present`);
    if (errs.length) fail(`${f}:\n  - ${errs.join('\n  - ')}`);
    if (e.draft && !INCLUDE_DRAFTS) { console.log(`skip  ${f} (draft)`); continue; }
    e._file = f;
    entries.push(e);
  }
  const slugs = new Set();
  for (const e of entries) { if (slugs.has(e.slug)) fail(`duplicate slug "${e.slug}"`); slugs.add(e.slug); }
  return entries.sort((a, b) => (a.date < b.date ? 1 : a.date > b.date ? -1 : 0));
}
function fail(msg) { console.error('build-work: ' + msg); process.exit(1); }

